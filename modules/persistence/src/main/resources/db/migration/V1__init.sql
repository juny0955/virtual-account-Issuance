-- 은행
CREATE TABLE bank (
    code VARCHAR(3) PRIMARY KEY,
    name VARCHAR(10) NOT NULL
);

-- 기관
CREATE TABLE org (
    code VARCHAR(5) PRIMARY KEY,
    name VARCHAR(200) NOT NULL
);

-- 가상계좌 원장
CREATE TABLE va (
    bank_cd VARCHAR(3) NOT NULL,
    va_no VARCHAR(20) NOT NULL,
    status VARCHAR(10) NOT NULL,
    reusable_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_va PRIMARY KEY (bank_cd, va_no),
    CONSTRAINT fk_va_bank FOREIGN KEY (bank_cd) REFERENCES bank (code)
) PARTITION BY LIST (bank_cd);

CREATE TABLE va_default PARTITION OF va DEFAULT;

-- 일반 및 기관 대량 요청: qty는 은행별 계좌 묶음 수
CREATE TABLE va_req (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(10) NOT NULL,
    org_cd VARCHAR(5) NOT NULL,
    qty INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_va_req_qty CHECK (qty > 0),
    CONSTRAINT fk_va_req_institution FOREIGN KEY (org_cd) REFERENCES org (code)
);

-- 요청별 은행 목록
CREATE TABLE va_req_bank (
    req_id BIGINT NOT NULL,
    bank_cd VARCHAR(3) NOT NULL,
    bank_order SMALLINT NOT NULL,
    CONSTRAINT ck_va_req_bank_order CHECK (bank_order BETWEEN 1 AND 20),
    CONSTRAINT uq_va_req_bank_order UNIQUE (req_id, bank_order),
    CONSTRAINT pk_va_req_bank PRIMARY KEY (req_id, bank_cd),
    CONSTRAINT fk_va_req_bank_req FOREIGN KEY (req_id) REFERENCES va_req (id),
    CONSTRAINT fk_va_req_bank_bank FOREIGN KEY (bank_cd) REFERENCES bank (code)
);

-- 요청 결과의 한 행에 해당하는 계좌 묶음
CREATE TABLE va_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    req_id BIGINT NOT NULL,
    issue_no INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_va_group_issue_no CHECK (issue_no > 0),
    CONSTRAINT uq_va_group_req_issue_no UNIQUE (req_id, issue_no),
    CONSTRAINT uq_va_group_req_id UNIQUE (req_id, id),
    CONSTRAINT fk_va_group_req FOREIGN KEY (req_id) REFERENCES va_req (id)
);

-- 각 묶음의 은행별 할당 이력
CREATE TABLE va_alloc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    req_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    bank_cd VARCHAR(3) NOT NULL,
    va_no VARCHAR(20) NOT NULL,
    allocated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMPTZ,
    CONSTRAINT ck_va_alloc_released_at CHECK (released_at IS NULL OR released_at >= allocated_at),
    CONSTRAINT fk_va_alloc_group FOREIGN KEY (req_id, group_id) REFERENCES va_group (req_id, id),
    CONSTRAINT fk_va_alloc_req_bank FOREIGN KEY (req_id, bank_cd) REFERENCES va_req_bank (req_id, bank_cd),
    CONSTRAINT fk_va_alloc_va FOREIGN KEY (bank_cd, va_no) REFERENCES va (bank_cd, va_no)
);

